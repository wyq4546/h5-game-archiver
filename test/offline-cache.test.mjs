import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import path from 'node:path';
import {mkdir,mkdtemp,writeFile,rm} from 'node:fs/promises';
import {completeArchiveAssets} from '../src/asset-completer.mjs';
import {assessCompleteness} from '../src/capture.mjs';
import {classifyOfflineCacheRequests,constructOfflineCacheDeclaration} from '../src/offline-cache.mjs';

test('Construct directory precache 404s require recorded worker provenance and a valid alternate entry',async t=>{
  const requests=[];
  const worker='const CACHE_NAME_PREFIX="c3offline";const OFFLINE_DATA_FILE="offline.js";async function UpdateCheck(){const fileList=(await (await fetch(OFFLINE_DATA_FILE)).json()).fileList;fileList.unshift("./");return caches.open(CACHE_NAME_PREFIX);}';
  const server=http.createServer((req,res)=>{requests.push(req.url);if(req.url==='/game/sw.js')res.end(worker);else if(req.url==='/game/offline.js')res.end(JSON.stringify({version:1,fileList:['c2runtime.js','data.js']}));else {res.writeHead(404);res.end('missing');}});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const temp=path.resolve('.tmp');await mkdir(temp,{recursive:true});const root=await mkdtemp(path.join(temp,'offline-cache-'));
  t.after(async()=>{server.closeAllConnections();await new Promise(resolve=>server.close(resolve));assert.equal(path.dirname(root),temp);await rm(root,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${server.address().port}/game/`;
  await mkdir(path.join(root,'scripts'));
  for(const [name,body] of Object.entries({'index.html':'<script src="scripts/register-sw.js"></script><script src="c2runtime.js"></script>','scripts/register-sw.js':'navigator.serviceWorker.register("sw.js",{scope:"./"});','c2runtime.js':'// Generated by Construct\nfunction cr_createRuntime(){}','data.js':'{"project":[]}','error.xml':'<Error>NoSuchKey</Error>'}))await writeFile(path.join(root,name),body);
  const manifest={gameUrl:base+'index.html',runtimeInspection:{engine:'Construct',coreReady:true},localReplay:{status:'passed'},resources:[
    ...['index.html','scripts/register-sw.js','c2runtime.js','data.js'].map(name=>({url:base+name,path:name,saved:true,status:200,method:'GET',bytes:1000,type:name==='index.html'?'document':'script'})),
    {url:base,path:'error.xml',saved:true,status:404,type:'fetch',method:'GET',requestSource:{type:'service-worker',url:base+'sw.js'}}
  ]};
  const stats=await completeArchiveAssets(root,manifest,{emit:()=>{}});
  assert.equal(stats.failedAssets,0);
  assert.ok(requests.includes('/game/sw.js'));
  assert.ok(requests.includes('/game/offline.js'));
  const failure=manifest.resources.find(r=>r.status===404);
  assert.equal(failure.nonCriticalFailure?.category,'construct-directory-precache');
  let result=assessCompleteness(manifest);
  assert.equal(result.status,'core-complete');
  assert.equal(result.failedResources,1);
  assert.ok(result.nonCriticalFailures.some(r=>r.url===base));
  assert.equal(failure.status,404,'keep the original HTTP response');
  assert.equal(failure.ignored,undefined,'do not discard the failure');
  for(const change of [
    {type:'document'},
    {requestSource:undefined},
    {requestSource:{type:'service-worker',url:base+'different-worker.js'}},
    {url:base+'required-config.json'},
    {status:503},
  ]){
    const copy=structuredClone(manifest);Object.assign(copy.resources.find(r=>r.status===404),change);
    assert.equal(assessCompleteness(copy).status,'incomplete',JSON.stringify(change));
  }
  const failedStartup=structuredClone(manifest);failedStartup.localReplay={status:'failed',error:'Missing native asset'};
  assert.equal(assessCompleteness(failedStartup).status,'incomplete');
  const missingEntry=structuredClone(manifest);missingEntry.resources=missingEntry.resources.filter(r=>r.type!=='document');
  assert.equal(assessCompleteness(missingEntry).status,'incomplete');
  const capturedWorker=manifest.resources.find(r=>r.url===base+'sw.js');
  await writeFile(path.join(root,capturedWorker.path),'self.addEventListener("fetch",()=>fetch("./"));');
  await completeArchiveAssets(root,manifest,{emit:()=>{}});
  assert.equal(failure.nonCriticalFailure,undefined,'a different worker must not inherit the old cache exemption');
  assert.equal(assessCompleteness(manifest).status,'incomplete');
});

test('minified Construct precache requires a fileList alias rather than any unshift call',()=>{
  const prefix='const OFFLINE_DATA_FILE="offline.json",CACHE_NAME_PREFIX="c3offline";';
  assert.deepEqual(constructOfflineCacheDeclaration(prefix+'const a=await t.json(),s=a.fileList;s.unshift("./");'),{manifest:'offline.json',cache:'c3offline'});
  assert.equal(constructOfflineCacheDeclaration(prefix+'const s=other;s.unshift("./");'),null);
});

test('Construct 2 inline HTML registration classifies only the proven worker directory precache',async t=>{
 const temp=path.resolve('.tmp');await mkdir(temp,{recursive:true});const root=await mkdtemp(path.join(temp,'c2-inline-'));t.after(()=>rm(root,{recursive:true,force:true}));
 const base='https://example.com/build/';const sources={
 'index.html':'<script>window.C2_RegisterSW=function(){navigator.serviceWorker.register("sw.js",{scope:"./"})}</script>',
 'sw.js':'const OFFLINE_DATA_FILE="offline.js";const CACHE_NAME_PREFIX="c2offline";const fileList=data.fileList;fileList.unshift("./");',
 'offline.js':'\uFEFF'+JSON.stringify({version:1,fileList:['c2runtime.js']}),
 'c2runtime.js':'// Construct runtime', 'error.html':'404'};
 for(const [name,text]of Object.entries(sources))await writeFile(path.join(root,name),text);
 const m={gameUrl:base+'index.html?session=1',runtimeInspection:{engine:'Construct',coreReady:true},resources:Object.keys(sources).filter(n=>n!=='error.html').map(name=>({url:base+name+(name==='index.html'?'?session=1':''),path:name,status:200,saved:true,type:name==='index.html'?'document':'script'}))};
 m.resources.push({url:base,path:'error.html',status:404,saved:true,type:'fetch',requestSource:{type:'service-worker',url:base+'sw.js'}});
 assert.equal((await classifyOfflineCacheRequests(root,m)).length,1);assert.equal(assessCompleteness(m).status,'core-complete');
 const bad=structuredClone(m);bad.resources.at(-1).url=base+'required.json';assert.equal((await classifyOfflineCacheRequests(root,bad)).length,0);assert.equal(assessCompleteness(bad).status,'incomplete');
 await writeFile(path.join(root,'index.html'),'<script>console.log("no worker registration")</script>');assert.equal((await classifyOfflineCacheRequests(root,m)).length,0);assert.equal(assessCompleteness(m).status,'incomplete');
});
